#!/usr/bin/env bash
# Mirrors the Proof of Spend specification from truway-xyz/soroban-contracts into this site.
# The specification is maintained next to its conformance tests; never edit the mirrored page.
#
# Usage: scripts/sync-spec.sh [path-to-soroban-contracts]   (default: ../soroban-contracts)
set -euo pipefail

SRC_REPO="${1:-../soroban-contracts}"
SRC="$SRC_REPO/docs/proof-of-spend.md"
BASE="https://github.com/truway-xyz/soroban-contracts/blob/main"
COMMIT="$(git -C "$SRC_REPO" rev-parse --short HEAD)"

[ -f "$SRC" ] || { echo "not found: $SRC" >&2; exit 1; }

for out in en/proof-of-spend/specification.md es/proof-of-spend/especificacion.md; do
  {
    echo '<!-- Generated by scripts/sync-spec.sh. Do not edit: change docs/proof-of-spend.md in truway-xyz/soroban-contracts. -->'
    echo
    if [[ "$out" == es/* ]]; then
      echo "> La especificación se publica en inglés, que es su versión normativa. Copiada de [\`soroban-contracts/docs/proof-of-spend.md\`]($BASE/docs/proof-of-spend.md) en el commit \`$COMMIT\`."
    else
      echo "> Mirrored from [\`soroban-contracts/docs/proof-of-spend.md\`]($BASE/docs/proof-of-spend.md) at commit \`$COMMIT\`. Open changes there."
    fi
    echo
    # Relative links in the source point inside soroban-contracts: make them absolute.
    sed -E \
      -e "s#\]\(\.\./([^)]+)\)#](${BASE}/\1)#g" \
      -e "s#\]\((adr/[^)]+|[a-z-]+\.md[^)]*)\)#](${BASE}/docs/\1)#g" \
      "$SRC"
  } > "$out"
  echo "wrote $out"
done
